const assert = require('node:assert/strict');
const {webcrypto} = require('node:crypto');
global.crypto = webcrypto;
require('../github_settings.js');
const settings = global.GitHubSettings;
const values = new Map();
const storage = {getItem: key => values.get(key), setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key)};

(async () => {
    storage.setItem(settings.storageKey, JSON.stringify({repository: 'fictional-owner/config', branch: 'main'}));
    const old = settings.read(storage);
    assert.equal(old.repository, 'fictional-owner/config');
    assert.equal(old.syncSecrets, true);
    assert.equal(old.vault, null);
    const password = 'fictional-unlock-password';
    const token = 'fictional-github-token';
    const vault = await settings.encrypt(token, password);
    const second = await settings.encrypt(token, password);
    assert.notEqual(vault.iv, second.iv);
    assert.notEqual(vault.salt, second.salt);
    assert.notEqual(vault.ciphertext, second.ciphertext);
    settings.write({...old, includeEnv: true, mode: 'replace', token, password}, {...vault, token}, storage);
    const persisted = [...values.values()].join('');
    assert.ok(!persisted.includes(token));
    assert.ok(!persisted.includes(password));
    assert.equal(await settings.decrypt(settings.read(storage).vault, password), token);
    assert.equal(settings.read(storage).mode, 'replace');
    await assert.rejects(() => settings.decrypt(vault, 'incorrect-password'), /解锁失败/);
    const corrupt = {...vault, ciphertext: Buffer.alloc(40).toString('base64')};
    await assert.rejects(() => settings.decrypt(corrupt, password), /解锁失败/);
    await assert.rejects(() => settings.decrypt({...vault, iterations: 1}, password), /格式无效/);
    await assert.rejects(() => settings.encrypt(token, 'short'), /至少 10/);
    assert.throws(() => settings.write(old, null, {setItem() { throw new Error(token); }}), error => !error.message.includes(token));
    settings.write(settings.read(storage), null, storage);
    assert.equal(settings.read(storage).vault, null);
    assert.equal(settings.read(storage).repository, old.repository);
    settings.clear(storage);
    assert.equal(settings.read(storage).repository, '');
    console.log('PASS encrypted PAT: reload, wrong password, tampering, random salt/IV, metadata-only migration, storage failure, forgetting');
})().catch(error => { console.error(error); process.exitCode = 1; });
